#= Compare Taylor's-law candidate fits on saved TL-prediction bins. =#

#/ Packages
using CSV
using DataFrames
using JLD2
using LsqFit
using Meris
using Statistics

PREDICTION_DIR = Meris.DATADIR * "macro/tl-prediction/"

categories = ["linguistic", "microbial", "social", "biology"]
min_points = 51

function parse_args!(args)
    global categories, min_points, PREDICTION_DIR

    for arg in args
        if startswith(arg, "--categories=")
            categories = split(last(split(arg, "="; limit=2)), ",")
        elseif startswith(arg, "--min-points=")
            min_points = parse(Int, last(split(arg, "="; limit=2)))
        elseif startswith(arg, "--prediction-dir=")
            PREDICTION_DIR = last(split(arg, "="; limit=2))
        elseif arg == "--help" || arg == "-h"
            println("""
            Usage:
              julia --project=julia-code julia-code/scripts/cli-scripts/macropatterns/tl-prediction-aic.jl [options]

            Inputs:
              Reads TL-prediction files from <prediction-dir>/<category>.jld2.
              Those files should be generated by tl-prediction.jl, which now consumes
              grouped downsampled datasets from data/downsampled.

            Options:
              --categories=a,b       Comma-separated subset. Default: linguistic,microbial,social,biology
              --min-points=N         Minimum points per bin to fit. Default: 51
              --prediction-dir=DIR   Directory with category TL-prediction .jld2 files.
                                     Default: $(PREDICTION_DIR)
            """)
            exit(0)
        else
            error("Unknown argument: $arg")
        end
    end

    PREDICTION_DIR = abspath(PREDICTION_DIR)
    mkpath(PREDICTION_DIR)
end

prediction_file(category) = joinpath(PREDICTION_DIR, "$(category).jld2")
output_file() = joinpath(PREDICTION_DIR, "tl-prediction-aic.jld2")
csv_file() = joinpath(PREDICTION_DIR, "tl-prediction-aic.csv")
summary_csv_file() = joinpath(PREDICTION_DIR, "tl-prediction-aic-class-summary.csv")

power_model(x, p) = p[1] .* x .^ p[2]
log_power_model(logx, p) = p[1] .+ p[2] .* logx
quadratic_model(x, p) = x .+ p[1] .* x .^ 2
log_quadratic_model(logx, p) = begin
    x = exp.(logx)
    log.(x .+ p[1] .* x .^ 2)
end

function gaussian_aic(model, x, y, p)
    residuals = y .- model(x, p)
    n = length(y)
    k = length(p)
    sse = sum(abs2, residuals)

    if n == 0 || !isfinite(sse)
        return (; sse, mse=Inf, rmse=Inf, mae=Inf, aic=Inf, loglikelihood=-Inf)
    end

    mse = sse / n
    rmse = sqrt(mse)
    mae = mean(abs.(residuals))

    if sse <= eps(Float64)
        return (; sse, mse, rmse, mae, aic=-Inf, loglikelihood=Inf)
    end

    σ2 = mse
    loglikelihood = -n / 2 * (log(2π) + log(σ2) + 1)
    aic = 2k - 2loglikelihood

    return (; sse, mse, rmse, mae, aic, loglikelihood)
end

function initial_power_params(x, y)
    positive = (x .> 0) .& (y .> 0)

    if count(positive) < 2
        return [1.0, 1.0]
    end

    logx = log.(x[positive])
    logy = log.(y[positive])
    X = hcat(ones(length(logx)), logx)
    coeffs = X \ logy

    a = exp(coeffs[1])
    b = coeffs[2]

    isfinite(a) || (a = 1.0)
    isfinite(b) || (b = 1.0)

    return [a, b]
end

function initial_log_power_params(x, y)
    p = initial_power_params(x, y)
    return [log(p[1]), p[2]]
end

function initial_quadratic_param(x, y)
    numerator = sum((x .^ 2) .* (y .- x))
    denominator = sum(x .^ 4)
    c = denominator > 0 ? numerator / denominator : 0.0
    isfinite(c) || (c = 0.0)
    c = max(c, 0.0)

    return [c]
end

function fit_candidate(
    category,
    class,
    coeff_bin,
    coeff_order,
    bin_center,
    model_name,
    response_scale,
    model,
    p0,
    x,
    y;
    lower=nothing,
    upper=nothing
)
    try
        fit = if isnothing(lower) && isnothing(upper)
            curve_fit(model, x, y, p0)
        else
            curve_fit(model, x, y, p0; lower=lower, upper=upper)
        end
        scores = gaussian_aic(model, x, y, fit.param)
        param_names = model_name == "power" ? "a,b" : "c"
        params = model_name == "power" ? [exp(fit.param[1]), fit.param[2]] : fit.param

        return (
            category=category,
            class=class,
            coeff_bin=coeff_bin,
            coeff_order=coeff_order,
            bin_center=bin_center,
            model=model_name,
            response_scale=response_scale,
            n=length(y),
            nparams=length(fit.param),
            param_names=param_names,
            params=join(string.(params), ","),
            sse=scores.sse,
            log_sse=scores.sse,
            log_mse=scores.mse,
            log_rmse=scores.rmse,
            mean_abs_log_error=scores.mae,
            loglikelihood=scores.loglikelihood,
            aic=scores.aic,
            converged=true,
            error=""
        )
    catch err
        return (
            category=category,
            class=class,
            coeff_bin=coeff_bin,
            coeff_order=coeff_order,
            bin_center=bin_center,
            model=model_name,
            response_scale=response_scale,
            n=length(y),
            nparams=length(p0),
            param_names=model_name == "power" ? "a,b" : "c",
            params="",
            sse=Inf,
            log_sse=Inf,
            log_mse=Inf,
            log_rmse=Inf,
            mean_abs_log_error=Inf,
            loglikelihood=-Inf,
            aic=Inf,
            converged=false,
            error=sprint(showerror, err)
        )
    end
end

function fit_bin(category, g)
    mean_col = :mean in propertynames(g) ? :mean : :mean_B
    var_col = :var in propertynames(g) ? :var : :var_B

    x = Float64.(g[!, mean_col])
    y = Float64.(g[!, var_col])
    finite = isfinite.(x) .& isfinite.(y) .& (x .> 0) .& (y .> 0)
    x = x[finite]
    y = y[finite]

    if length(y) < min_points
        return DataFrame()
    end

    class = first(g.class)
    coeff_bin = first(g.coeff_bin)
    coeff_order = hasproperty(g, :coeff_order) ? first(g.coeff_order) : missing
    bin_center = hasproperty(g, :bin_center) ? first(g.bin_center) : missing

    return DataFrame([
        fit_candidate(
            category,
            class,
            coeff_bin,
            coeff_order,
            bin_center,
            "power",
            "log_variance",
            log_power_model,
            initial_log_power_params(x, y),
            log.(x),
            log.(y)
        ),
        fit_candidate(
            category,
            class,
            coeff_bin,
            coeff_order,
            bin_center,
            "quadratic",
            "log_variance",
            log_quadratic_model,
            initial_quadratic_param(x, y),
            log.(x),
            log.(y);
            lower=[0.0],
            upper=[Inf]
        )
    ])
end

function fit_category(category)
    filename = prediction_file(category)
    isfile(filename) || error(
        "Missing TL-prediction file: $filename. " *
        "Run julia --project=julia-code julia-code/scripts/cli-scripts/macropatterns/tl-prediction.jl first."
    )

    @info "Loading $filename"
    jldb = JLD2.load(filename)
    component_bins = jldb["component_bins"]

    grouped = groupby(component_bins, [:class, :coeff_bin])
    dfs = DataFrame[]

    for g in grouped
        bindf = fit_bin(category, g)
        isempty(bindf) || push!(dfs, bindf)
    end

    return isempty(dfs) ? DataFrame() : vcat(dfs...)
end

function add_missing_model_column!(df, col)
    col in Symbol.(names(df)) || (df[!, col] .= 0)
    return df
end

function rename_model_columns!(df, prefix)
    mapping = Dict{Symbol, Symbol}()

    :power in Symbol.(names(df)) && (mapping[:power] = Symbol(prefix, "_power"))
    :quadratic in Symbol.(names(df)) && (mapping[:quadratic] = Symbol(prefix, "_quadratic"))

    rename!(df, mapping)
    return df
end

function model_metric_wide(df, value_col, prefix)
    wide = unstack(
        select(df, :category, :class, :model, value_col),
        [:category, :class],
        :model,
        value_col
    )

    return rename_model_columns!(wide, prefix)
end

function class_summary(aicdf)
    winners = combine(groupby(aicdf, [:category, :class, :coeff_bin])) do df
        best = df[argmin(df.aic), :]
        (; winner=best.model, n=best.n)
    end

    win_counts = unstack(
        combine(groupby(winners, [:category, :class, :winner]), nrow => :nwins),
        [:category, :class],
        :winner,
        :nwins;
        fill=0
    )

    add_missing_model_column!(win_counts, :power)
    add_missing_model_column!(win_counts, :quadratic)

    win_counts.total_bins = win_counts.power .+ win_counts.quadratic
    win_counts.best_model = ifelse.(
        win_counts.power .> win_counts.quadratic,
        "power",
        ifelse.(win_counts.quadratic .> win_counts.power, "quadratic", "tie")
    )
    win_counts.power_fraction = win_counts.power ./ win_counts.total_bins

    metrics = combine(
        groupby(aicdf, [:category, :class, :model]),
        :aic => mean => :mean_aic,
        :log_rmse => mean => :mean_log_rmse
    )

    summary = leftjoin(
        win_counts,
        model_metric_wide(metrics, :mean_aic, "mean_aic"),
        on=[:category, :class]
    )
    summary = leftjoin(
        summary,
        model_metric_wide(metrics, :mean_log_rmse, "mean_log_rmse"),
        on=[:category, :class]
    )

    select!(
        summary,
        :category,
        :class,
        :quadratic,
        :power,
        :best_model,
        :power_fraction,
        :mean_aic_quadratic,
        :mean_aic_power,
        :mean_log_rmse_quadratic,
        :mean_log_rmse_power
    )

    sort!(summary, [:category, :class])

    return summary
end

parse_args!(ARGS)

aicdf = vcat([fit_category(category) for category in categories]...)

if !isempty(aicdf)
    transform!(
        groupby(aicdf, [:category, :class, :coeff_bin]),
        :aic => (x -> x .- minimum(x)) => :delta_aic
    )

    sort!(aicdf, [:category, :class, :coeff_bin, :aic])
end

summarydf = isempty(aicdf) ? DataFrame() : class_summary(aicdf)

OUTFILE = output_file()
CSVFILE = csv_file()
SUMMARY_CSVFILE = summary_csv_file()

jldsave(OUTFILE; aicdf=aicdf, prediction_dir=PREDICTION_DIR, categories=categories, min_points=min_points)
CSV.write(CSVFILE, aicdf)
CSV.write(SUMMARY_CSVFILE, summarydf)

@info "Saved AIC dataframe" OUTFILE CSVFILE SUMMARY_CSVFILE nrow(aicdf)
